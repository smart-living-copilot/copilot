@router.post("/message")
async def post_message(
    body: A2AMessage,
    request: Request,
    _ok: Any = None,
):
    """Legacy simple message endpoint.  Returns the same format as before."""
    graph = _agent_graph(request)
    if graph is None:
        raise HTTPException(status_code=503, detail="Agent graph not ready")
    registry = _run_registry(request)

    executor_url = _code_executor_url(request)
    api_key = _api_key(request)
    base_url = str(request.base_url).rstrip("/")
    thread_id = body.threadId or f"embed-ephemeral-{uuid4().hex}"
    run_id = uuid4().hex

    try:
        task = await _run_agent(graph, registry, body.message, thread_id, run_id, executor_url, api_key, base_url, body.attachments or None)
    except HTTPException as exc:
        raise exc

    # Collect events for backward compat
    events = []
    if task.status.message:
        for p in task.status.message.parts:
            if p.text:
                events.append({"type": "text", "content": p.text})
    for art in task.artifacts:
        for p in art.parts:
            events.append({
                "type": "A2A_ARTIFACTS",
                "artifacts": [{
                    "filename": art.artifact_id,
                    "kind": "image" if "image" in p.mime_type else "plotly",
                    "media_type": p.mime_type,
                    "base64": p.inline_data if p.inline_data else "",
                }],
            })

    return {
        "ok": task.status.state == TaskState.COMPLETED,
        "thread_id": thread_id,
        "run_id": run_id,
        "events": events,
        "task": task.model_dump(),
    }
