@router.get("/artifacts/{filename:path}")
async def proxy_artifact(filename: str, request: Request):
    """Proxy artifact files from the code executor.

    Public endpoint — no authentication required.
    Artifacts are files generated by the agent (plots, CSVs, etc.)
    and are served read-only.
    """
    if "/" in filename or "\\" in filename or ".." in filename:
        raise HTTPException(status_code=400, detail="Invalid filename")

    executor_url = _code_executor_url(request)
    api_key = _api_key(request)
    result = await _fetch_artifact(executor_url, filename, api_key)
    if result is None:
        raise HTTPException(status_code=404, detail="Artifact not found")

    return Response(
        content=result["body"],
        media_type=result["content_type"],
        headers={"Content-Disposition": f'inline; filename="{filename}"'},
    )


_MAX_UPLOAD_SIZE = 50 * 1024 * 1024  # 50 MB
_ALLOWED_EXTENSIONS = {
    ".csv", ".json", ".xml", ".txt", ".log", ".parquet", ".feather", ".orc",
    ".xlsx", ".xls", ".ods", ".tsv", ".psv",
    ".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg",
    ".html", ".htm", ".md", ".rst",
    ".zip", ".gz", ".bz2", ".xz", ".zst",
    ".npy", ".npz", ".pkl", ".pickle", ".joblib",
    ".h5", ".hdf5", ".nc", ".netcdf",
    ".yaml", ".yml", ".toml", ".cfg", ".ini",
    ".py", ".r", ".sql", ".sh",
}


@router.post("/upload")
async def upload_artifact(file: UploadFile, request: Request):
    """Upload a data file for the Python sandbox.

    Public endpoint — no authentication required.
    Only files with data-oriented extensions are accepted
    (see ``_ALLOWED_EXTENSIONS``).  Max size is 50 MB.

    Returns the filename that can be used with ``/api/a2a/artifacts/{filename}``
    and accessed in Python code via ``/tmp/code-executor-artifacts/{filename}``.
    """
    # Check extension
    ext = ""
    if file.filename and "." in file.filename:
        ext = "." + file.filename.rsplit(".", 1)[1].lower()
    if ext and ext not in _ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=400, detail=f"File extension '{ext}' is not allowed")

    content = await file.read()
    if len(content) > _MAX_UPLOAD_SIZE:
        raise HTTPException(status_code=413, detail=f"File too large (max {_MAX_UPLOAD_SIZE // 1024 // 1024} MB)")

    executor_url = _code_executor_url(request)
    api_key = _api_key(request)

    # Try the code executor's upload endpoint first
    ext = ""
    if file.filename and "." in file.filename:
        ext = "." + file.filename.rsplit(".", 1)[1]
    filename = f"upload-{uuid4().hex}{ext}"

    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            resp = await client.post(
                f"{executor_url}/upload",
                files={"file": (filename, content, file.content_type or "application/octet-stream")},
                headers={} if not api_key else {"Authorization": f"Bearer {api_key}"},
            )
            resp.raise_for_status()
            upload_data = resp.json()
            filename = upload_data.get("filename", filename)
    except Exception as exc:
        logger.warning("Code executor upload failed, storing locally: %s", exc)
        # Fallback: store in a local temp directory
        import tempfile
        local_dir = os.path.join(tempfile.gettempdir(), "a2a-uploads")
        os.makedirs(local_dir, exist_ok=True)
        local_path = os.path.join(local_dir, filename)
        with open(local_path, "wb") as f:
            f.write(content)
        # Also serve it via the proxy by adding a local-file fallback in _fetch_artifact
        logger.info("Saved uploaded file locally: %s (%d bytes)", local_path, len(content))

    return {"filename": filename, "size_bytes": len(content), "url": f"{str(request.base_url).rstrip('/')}/api/a2a/artifacts/{filename}"}


# ---------------------------------------------------------------------------
# Artifact fetching from the code executor
# ---------------------------------------------------------------------------


async def _fetch_artifact(
    executor_url: str, filename: str, api_key: str
) -> dict[str, Any] | None:
    safe = "/" not in filename and "\\" not in filename and ".." not in filename
    if not safe or not filename:
        return None
    url = f"{executor_url}/artifacts/{filename}"
    headers = {}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"
    try:
        async with httpx.AsyncClient(timeout=10.0) as client:
            resp = await client.get(url, headers=headers)
            resp.raise_for_status()
        body = resp.content
        return {"filename": filename, "body": body, "content_type": resp.headers.get("content-type", "application/octet-stream")}
    except httpx.HTTPStatusError as exc:
        if exc.response.status_code == 404:
            # Fallback: check local a2a-uploads directory
            import tempfile
            local_dir = os.path.join(tempfile.gettempdir(), "a2a-uploads")
            local_path = os.path.join(local_dir, filename)
            if os.path.isfile(local_path):
                with open(local_path, "rb") as f:
                    body = f.read()
                ct = "application/octet-stream"
                if filename.endswith(".csv"):
                    ct = "text/csv"
                elif filename.endswith(".json"):
                    ct = "application/json"
                elif filename.endswith(".png"):
                    ct = "image/png"
                return {"filename": filename, "body": body, "content_type": ct}
        logger.warning("Could not fetch artifact %s: %s", filename, exc)
        return None
    except Exception as exc:
        logger.warning("Could not fetch artifact %s: %s", filename, exc)
        return None


async def _collect_artifact_parts(events: list[Any], executor_url: str, api_key: str, base_url: str = "") -> list[Part]:
    """Scan events for artifact filenames, fetch from code executor, return as A2A Parts."""
    filenames: set[str] = set()
    for event in events:
        event_dict = _as_dict(event)
        if not event_dict:
            continue
        if event_dict.get("type") == "RAW":
            raw = event_dict.get("event") or {}
            if not isinstance(raw, dict):
                continue
            if raw.get("event") in ("on_tool_end", "on_chain_end"):
                output = raw.get("data", {}).get("output") or {}
                if not isinstance(output, dict):
                    continue
                content = output.get("content")
                if isinstance(content, str) and "artifacts" in content:
                    try:
                        parsed = json.loads(content)
                        if isinstance(parsed, dict):
                            for art in parsed.get("artifacts", []):
                                fn = art.get("filename") if isinstance(art, dict) else None
                                if isinstance(fn, str) and fn:
                                    filenames.add(fn)
                    except Exception:
                        pass

    if not filenames:
        return []

    results = await asyncio.gather(
        *[_fetch_artifact(executor_url, fn, api_key) for fn in filenames],
        return_exceptions=True,
    )
    parts: list[Part] = []
    for r in results:
        if not isinstance(r, dict):
            continue
        fn = r["filename"]
        body = r["body"]
        ct = r["content_type"]
        art_url = f"{base_url}/api/a2a/artifacts/{fn}" if base_url else ""
        if fn.endswith(".png"):
            parts.append(make_image_part(base64.b64encode(body).decode(), "image/png", url=art_url))
        elif fn.endswith((".html", ".json")):
            parts.append(Part(text="", mime_type="text/html", url=art_url, inline_data=body.decode("utf-8", errors="replace")))
        else:
            parts.append(make_image_part(base64.b64encode(body).decode(), ct, url=art_url))
    return parts


