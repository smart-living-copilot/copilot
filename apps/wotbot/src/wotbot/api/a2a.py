def _as_dict(obj: Any) -> dict | None:
    """Normalize an AG-UI event (Pydantic model / dict) to a plain dict."""
    if hasattr(obj, "model_dump"):
        return obj.model_dump()
    if hasattr(obj, "dict"):
        return obj.dict()
    if isinstance(obj, dict):
        return obj
    return None


def _build_graph_input(content_blocks: list[dict[str, Any]]) -> dict[str, Any]:
    """Build the LangGraph input for one user turn."""
    return {
        "messages": [
            {
                "id": f"msg-{uuid4().hex}",
                "role": "user",
                "content": content_blocks,
            }
        ]
    }


async def _stream_raw_events(
    graph: Any,
    registry: RunRegistry,
    thread_id: str,
    content_blocks: list[dict[str, Any]],
) -> AsyncGenerator[dict[str, Any], None]:
    """Run the graph for one turn, yielding RAW-wrapped LangGraph events.

    The A2A response builders below read ``on_chat_model_end``/``on_tool_end``
    payloads, so the graph's ``astream_events`` output is wrapped in the same
    ``{"type": "RAW", "event": ...}`` envelope the AG-UI runtime used to emit.
    The thread lock is shared with the chat routes so an external agent and the
    UI cannot drive the same thread at once.
    """
    config = {"configurable": {"thread_id": thread_id}}
    async with registry.thread_lock(thread_id):
        async for event in graph.astream_events(
            _build_graph_input(content_blocks),
            config=config,
            version="v2",
        ):
            yield {"type": "RAW", "event": event}


async def _upload_attachments(
    attachments: list[Attachment],
    executor_url: str,
    api_key: str,
    base_url: str,
) -> list[dict[str, Any]]:
    """Upload data attachments to the code executor; return extra content blocks.

    Images go to the vision LLM as-is.  Text/file attachments are uploaded to
    the code executor so the Python sandbox can access them, keeping large data
    out of the LLM context.
    """
    content_blocks: list[dict[str, Any]] = []
    for att in attachments:
        if att.type == "image" and att.data:
            content_blocks.append({"type": "image_url", "image_url": {"url": att.data}})
        elif att.type in ("text", "file") and att.data:
            try:
                data_bytes = base64.b64decode(att.data)
                ext = ".bin"
                if att.contentType == "text/csv":
                    ext = ".csv"
                elif att.contentType == "application/json":
                    ext = ".json"
                elif "text/" in att.contentType:
                    ext = ".txt"
                elif "xml" in att.contentType:
                    ext = ".xml"
                elif att.displayName and "." in att.displayName:
                    ext = "." + att.displayName.rsplit(".", 1)[1]

                filename = f"upload-{uuid4().hex}{ext}"
                async with httpx.AsyncClient(timeout=30.0) as client:
                    resp = await client.post(
                        f"{executor_url}/upload",
                        files={"file": (filename, data_bytes, att.contentType or "application/octet-stream")},
                        headers={} if not api_key else {"Authorization": f"Bearer {api_key}"},
                    )
                    resp.raise_for_status()
                    stored_filename = resp.json().get("filename", filename)

                label = att.displayName or stored_filename
                content_blocks.append({
                    "type": "text",
                    "text": (
                        f"[Uploaded file: {label}]\n"
                        f"The file is available at: {base_url}/api/a2a/artifacts/{stored_filename}\n"
                        f"To access it in Python use: /tmp/code-executor-artifacts/{stored_filename}\n"
                        f"Size: {len(data_bytes)} bytes"
                    ),
                })
            except Exception as exc:
                logger.warning("Failed to upload attachment to code executor: %s", exc)
                try:
                    decoded = base64.b64decode(att.data).decode("utf-8", errors="replace")
                    content_blocks.append({"type": "text", "text": f"[Attachment: {att.displayName or 'file'} ({att.contentType}) — upload failed, inline below]\n{decoded[:5000]}"})
                except Exception:
                    content_blocks.append({"type": "text", "text": f"[Attachment: {att.displayName or 'file'} ({att.contentType}) — {len(att.data)} base64 chars, upload failed]"})
    return content_blocks


def _extract_response_text(events: list[Any]) -> str:
    """Return the last non-JSON assistant text found in AG-UI events."""
    response_text = "(no response)"
    for event in events:
        ed = _as_dict(event)
        if not ed:
            continue
        if ed.get("type") == "RAW":
            raw = ed.get("event") or {}
            if raw.get("event") == "on_chat_model_end":
                output = raw.get("data", {}).get("output") or {}
                content = output.get("content") or ""
                if isinstance(content, str) and len(content) > 10:
                    if not (content.strip().startswith("{") and content.strip().endswith("}")):
                        response_text = content
    return response_text


def _build_task(run_id: str, thread_id: str, response_text: str, artifact_parts: list[Part]) -> Task:
    """Build a completed A2A Task with response text and artifacts."""
    task = Task(
        id=run_id,
        context_id=thread_id,
        status=TaskStatus(
            state=TaskState.COMPLETED,
            message=make_message(response_text, role=Role.ASSISTANT),
        ),
    )
    if artifact_parts:
        task.artifacts.append(
            Artifact(
                artifact_id=str(uuid4()),
                name="Agent Output",
                description="Visualizations and files generated by the agent",
                parts=artifact_parts,
            )
        )
    return task


def _parse_a2a_message(params: dict[str, Any]) -> tuple[str, str, list[Attachment]]:
    """Extract ``(message_text, context_id, attachments)`` from A2A ``params``."""
    message_text = ""
    context_id = ""
    attachments: list[Attachment] = []

    if "message" not in params:
        return message_text, context_id, attachments

    msg_data = params["message"]
    if isinstance(msg_data, dict):
        parts = msg_data.get("parts", [])
        if parts and isinstance(parts, list):
            for p in parts:
                if isinstance(p, dict) and p.get("text"):
                    message_text += p["text"] + "\n"
        context_id = msg_data.get("context_id", "")
        # Classify inline data by mime type
        for p in parts:
            if isinstance(p, dict) and p.get("inline_data"):
                mime = (p.get("mime_type") or "").lower()
                if mime.startswith("image/"):
                    attachments.append(Attachment(type="image", data=p["inline_data"], contentType=mime, displayName=p.get("file_name", "")))
                elif mime.startswith(("text/", "application/json", "application/csv", "application/xml")):
                    attachments.append(Attachment(type="text", data=p["inline_data"], contentType=mime, displayName=p.get("file_name", "")))
                else:
                    attachments.append(Attachment(type="file", data=p["inline_data"], contentType=mime, displayName=p.get("file_name", "")))
    elif isinstance(msg_data, str):
        message_text = msg_data

    return message_text.strip(), context_id, attachments


# ---------------------------------------------------------------------------
# Run the agent and produce a Task result
# ---------------------------------------------------------------------------


async def _run_agent(
    graph: Any,
    registry: RunRegistry,
    message_text: str,
    thread_id: str,
    run_id: str,
    executor_url: str,
    api_key: str,
    base_url: str = "",
    attachments: list[Attachment] | None = None,
) -> Task:
    """Run the WoTBot agent and return a completed Task with response text + artifacts.

    Data attachments (``text`` and ``file`` types) are **uploaded to the code
    executor** so they can be accessed by the Python sandbox.  The agent receives
    a message telling it the filename, avoiding large data in the LLM context.
    """
    content_blocks: list[dict[str, Any]] = [{"type": "text", "text": message_text}]
    if attachments:
        content_blocks.extend(await _upload_attachments(attachments, executor_url, api_key, base_url))

    events: list[Any] = []
    try:
        async for event in _stream_raw_events(graph, registry, thread_id, content_blocks):
            events.append(event)
    except asyncio.CancelledError:
        raise HTTPException(status_code=499, detail="Request cancelled")
    except Exception as exc:
        logger.exception("A2A run failed: %s", exc)
        raise HTTPException(status_code=500, detail=str(exc))

    response_text = _extract_response_text(events)
    artifact_parts = await _collect_artifact_parts(events, executor_url, api_key, base_url)
    return _build_task(run_id, thread_id, response_text, artifact_parts)


# ---------------------------------------------------------------------------
# Streaming agent runner — yields SSE events
# ---------------------------------------------------------------------------


async def _run_agent_streaming(
    graph: Any,
    registry: RunRegistry,
    message_text: str,
    thread_id: str,
    run_id: str,
    executor_url: str,
    api_key: str,
    base_url: str = "",
    attachments: list[Attachment] | None = None,
) -> AsyncGenerator[str, None]:
    """Run the WoTBot agent and yield SSE ``TaskStatusUpdateEvent`` chunks.

    Each yielded string is a complete SSE message (``data: {{...}}\n\n``).
    The final event has ``final: true``.
    """
    content_blocks: list[dict[str, Any]] = [{"type": "text", "text": message_text}]
    if attachments:
        content_blocks.extend(await _upload_attachments(attachments, executor_url, api_key, base_url))

    def _sse(event: TaskStatusUpdateEvent) -> str:
        return f"data: {event.model_dump_json()}\n\n"

    # 1. Initial working event
    yield _sse(TaskStatusUpdateEvent(
        task_id=run_id,
        context_id=thread_id,
        status=TaskStatus(state=TaskState.WORKING),
        final=False,
    ))

    # 2. Run the agent — yield progress events inline
    events: list[Any] = []
    latest_text = ""

    try:
        async for event in _stream_raw_events(graph, registry, thread_id, content_blocks):
            events.append(event)
            ed = _as_dict(event)
            if not ed or ed.get("type") != "RAW":
                continue
            raw = ed.get("event") or {}
            if raw.get("event") == "on_chat_model_end":
                output = raw.get("data", {}).get("output") or {}
                content = output.get("content") or ""
                if isinstance(content, str) and len(content) > 10:
                    if not (content.strip().startswith("{") and content.strip().endswith("}")):
                        latest_text = content
                        yield _sse(TaskStatusUpdateEvent(
                            task_id=run_id,
                            context_id=thread_id,
                            status=TaskStatus(
                                state=TaskState.WORKING,
                                message=make_message(content, role=Role.ASSISTANT),
                            ),
                            final=False,
                        ))
            elif raw.get("event") == "on_tool_end":
                yield _sse(TaskStatusUpdateEvent(
                    task_id=run_id,
                    context_id=thread_id,
                    status=TaskStatus(
                        state=TaskState.WORKING,
                        message=make_message(f"[Tool completed: {raw.get('name', 'unknown')}]", role=Role.ASSISTANT),
                    ),
                    final=False,
                ))
    except asyncio.CancelledError:
        yield _sse(TaskStatusUpdateEvent(
            task_id=run_id, context_id=thread_id,
            status=TaskStatus(state=TaskState.CANCELED), final=True,
        ))
        return
    except Exception as exc:
        logger.exception("A2A stream run failed: %s", exc)
        yield _sse(TaskStatusUpdateEvent(
            task_id=run_id, context_id=thread_id,
            status=TaskStatus(
                state=TaskState.FAILED,
                message=make_message(str(exc), role=Role.ASSISTANT),
            ),
            final=True,
        ))
        return

    # 3. Build final Task with artifacts
    response_text = latest_text or _extract_response_text(events) or "(no response)"
    artifact_parts = await _collect_artifact_parts(events, executor_url, api_key, base_url)
    task = _build_task(run_id, thread_id, response_text, artifact_parts)

    # 4. Final event
    yield _sse(TaskStatusUpdateEvent(
        task_id=run_id, context_id=thread_id,
        status=task.status, final=True,
    ))


@router.post("/jsonrpc")
async def jsonrpc_endpoint(body: JSONRPCRequest, request: Request):
    """JSON-RPC 2.0 endpoint for the A2A protocol.

    Supported methods:
      - ``sendMessage`` — send a message, get a Task back
      - ``sendMessageStream`` — send a message, get a streaming TaskStatusUpdateEvent
    """
    graph = _agent_graph(request)
    if graph is None:
        return JSONResponse(
            content=JSONRPCResponse(id=body.id, error=JSONRPCError(code=-32000, message="Agent graph not ready")).model_dump(),
            status_code=503,
        )
    registry = _run_registry(request)

    if body.method == "sendMessage":
        return await _handle_send_message(body, graph, registry, request)
    elif body.method == "sendMessageStream":
        return await _handle_send_message_stream(body, graph, registry, request)
    else:
        return JSONResponse(
            content=JSONRPCResponse(id=body.id, error=JSONRPCError(code=-32601, message=f"Method not found: {body.method}")).model_dump(),
            status_code=400,
        )


async def _handle_send_message(
    body: JSONRPCRequest, graph: Any, registry: RunRegistry, request: Request
) -> JSONResponse:
    """Handle a sendMessage JSON-RPC call."""
    executor_url = _code_executor_url(request)
    api_key = _api_key(request)
    message_text, context_id, attachments = _parse_a2a_message(body.params or {})

    if not message_text:
        return JSONResponse(
            content=JSONRPCResponse(id=body.id, error=JSONRPCError(code=-32602, message="No message text provided")).model_dump(),
            status_code=400,
        )

    thread_id = context_id or f"a2a-{uuid4().hex}"
    run_id = uuid4().hex
    base_url = str(request.base_url).rstrip("/")

    try:
        task = await _run_agent(graph, registry, message_text, thread_id, run_id, executor_url, api_key, base_url, attachments)
    except HTTPException as exc:
        task = Task(
            id=run_id,
            context_id=thread_id,
            status=TaskStatus(state=TaskState.FAILED, message=make_message(str(exc.detail), role=Role.ASSISTANT)),
        )

    result = SendMessageResult(task=task)
    return JSONResponse(
        content=JSONRPCResponse(id=body.id, result=result.model_dump()).model_dump(),
    )


async def _handle_send_message_stream(
    body: JSONRPCRequest, graph: Any, registry: RunRegistry, request: Request
) -> StreamingResponse:
    """Handle a sendMessageStream call — returns a SSE streaming response.

    Yields ``TaskStatusUpdateEvent`` chunks as the agent runs.
    """
    executor_url = _code_executor_url(request)
    api_key = _api_key(request)
    message_text, context_id, attachments = _parse_a2a_message(body.params or {})

    if not message_text:
        error_event = TaskStatusUpdateEvent(
            task_id="",
            status=TaskStatus(
                state=TaskState.FAILED,
                message=make_message("No message text provided", role=Role.ASSISTANT),
            ),
            final=True,
        )
        return StreamingResponse(
            content=f"data: {error_event.model_dump_json()}\n\n",
            media_type="text/event-stream",
            headers={"X-ACCEPTED": "text/event-stream"},
        )

    thread_id = context_id or f"a2a-{uuid4().hex}"
    run_id = uuid4().hex
    base_url = str(request.base_url).rstrip("/")

    return StreamingResponse(
        content=_run_agent_streaming(graph, registry, message_text, thread_id, run_id, executor_url, api_key, base_url, attachments),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )


